"""What spiral_geometry.py computes: logarithmic auxiliary vs Archimedean capture spiral waypoints.

Waypoints are generated by importing spider_web_htn_updated.utils from the private clone at 61d18d8
(AUXILIARY_SPIRAL_WAYPOINTS / CAPTURE_SPIRAL_WAYPOINTS, i.e. spiral_geometry.py driven by config.yaml).
Panel (d) uses work/core/derived/spiral_fraction_sweep_61d18d8.json (rerun_spiral_fraction.py).
"""
import json
import math
import os
import sys

import matplotlib.pyplot as plt
import numpy as np

from _common import DERIVED, FIG, W, thread_color
import plotstyle

sys.path.insert(0, os.path.join(W, "work", "core", "repo"))
from spider_web_htn_updated import utils as U  # noqa: E402
from spider_web_htn_updated.config_loader import CONFIG  # noqa: E402

plotstyle.apply()
hub = U.NODE_COORDS["proto_hub"]
AUX, CAP = U.AUXILIARY_SPIRAL_WAYPOINTS, U.CAPTURE_SPIRAL_WAYPOINTS
ca, cc = thread_color("auxiliary_spiral"), thread_color("capture_spiral")


def polar(wps):
    out = []
    for i, (name, (x, y), src) in enumerate(wps):
        ax_, ay_ = U.NODE_COORDS[src]
        r_t = math.hypot(ax_ - hub[0], ay_ - hub[1])
        r = math.hypot(x - hub[0], y - hub[1])
        out.append((i, src, r, r / r_t))
    return out


pa, pc = polar(AUX), polar(CAP)
ndir = len(CONFIG["domain"]["spiral_nodes"]["auxiliary"])

fig, axs = plt.subplots(2, 2, figsize=(7.0, 6.0))
a, b, c, d = axs.ravel()

# (a) xy
for (x1, y1), (x2, y2) in [((0, 0), (0, 18)), ((16, 0), (16, 18)), ((0, 0), (16, 0)), ((0, 9), (16, 9))]:
    a.plot([x1, x2], [y1, y2], color="#D0D0D0", lw=3, zorder=0)
for anc in CONFIG["domain"]["radii_anchor_order"]:
    x, y = U.NODE_COORDS[anc]
    a.plot([hub[0], x], [hub[1], y], color=thread_color("radius"), lw=0.8, alpha=0.6)
xs = [hub[0]] + [p[0] for _, p, _ in AUX]
ys = [hub[1]] + [p[1] for _, p, _ in AUX]
a.plot(xs, ys, "-o", color=ca, ms=2.4, lw=1.0, label=f"auxiliary (log), {len(AUX)} waypoints")
xs = [hub[0]] + [p[0] for _, p, _ in CAP]
ys = [hub[1]] + [p[1] for _, p, _ in CAP]
a.plot(xs, ys, "-o", color=cc, ms=2.4, lw=1.0, label=f"capture (Archimedean), {len(CAP)} waypoints")
br = U.NODE_COORDS["anchor_bottom_right"]
a.annotate("no spiral\nwaypoints on\nthis radius", xy=(10.5, 6.0), xytext=(12.2, 1.6), fontsize=6.3,
           arrowprops=dict(arrowstyle="->", lw=0.6))
a.plot(*hub, "ko", ms=3)
a.set_aspect("equal")
a.set_xlim(-1, 17)
a.set_ylim(-1, 19)
a.grid(False)
a.set_xlabel("x (cm)")
a.set_ylabel("y (cm)")
a.legend(fontsize=6.3, loc="upper center", bbox_to_anchor=(0.5, 1.13), ncol=1)
a.set_title("(a)", fontsize=8.5, loc="left")

# (b) normalised radius vs waypoint index / rotations
for pts, col, lab in ((pa, ca, "auxiliary: $r_i=r_0^{1-f}\\,r_T^{\\,f}$"), (pc, cc, "capture: $r_i=r_T+(r_0-r_T)f$")):
    i = np.array([p[0] for p in pts])
    rel = np.array([p[3] for p in pts])
    b.plot(i / ndir, rel, "o-", color=col, ms=3, label=lab)
b.set_xlabel(f"Rotations about hub (waypoint index / {ndir})")
b.set_ylabel(r"$r / r_T$ (fraction of anchor radius)")
b.set_ylim(0, 1.25)
b.legend(fontsize=6.6, loc="upper center", bbox_to_anchor=(0.5, 1.0), frameon=True, facecolor="white", edgecolor="none")
b.set_title("(b)", fontsize=8.5, loc="left")

# (c) mesh spacing: radial gap between successive loops along the same direction
for pts, col, lab, m in ((pa, ca, "auxiliary", "o"), (pc, cc, "capture", "s")):
    by_dir = {}
    for i, src, r, rel in pts:
        by_dir.setdefault(src, []).append((i, r))
    gaps = []
    for src, seq in by_dir.items():
        for (i0, r0), (i1, r1) in zip(seq, seq[1:]):
            gaps.append((i1 / ndir, abs(r1 - r0) * 10))   # mm
    gaps.sort()
    c.plot([g[0] for g in gaps], [g[1] for g in gaps], m, color=col, ms=3.2, label=lab, alpha=0.85)
emp = CONFIG["empirical"]["mesh_size_mm"]
c.axhline(emp, color="black", ls="--", lw=0.9, label=f"config empirical.mesh_size_mm = {emp}")
c.set_xlabel("Rotations about hub (later loop of each pair)")
c.set_ylabel("Radial gap between successive loops (mm)")
c.set_ylim(0, None)
c.legend(fontsize=6.4, loc="upper left")
c.set_title("(c)", fontsize=8.5, loc="left")

# (d) energy vs start_radius_fraction (re-run sweep)
sw = json.load(open(os.path.join(DERIVED, "spiral_fraction_sweep_61d18d8.json")))
f = [r["start_radius_fraction"] for r in sw]
d.plot(f, [r["total"] for r in sw], "o-", color=plotstyle.AGENT_COLORS["HTN"], ms=3.5, label="whole plan")
d.plot(f, [r["auxiliary_spiral"] for r in sw], "o-", color=ca, ms=3.2, label="auxiliary-spiral phase")
d.plot(f, [r["capture_spiral"] for r in sw], "s-", color=cc, ms=3.2, label="capture-spiral phase")
d.axvline(CONFIG["domain"]["spiral"]["start_radius_fraction"], color="grey", lw=0.8, ls=":")
d.text(0.205, 400, "shipped\n0.20", fontsize=6.5, color="grey")
d.set_xlabel("domain.spiral.start_radius_fraction")
d.set_ylabel("Energy (cm)")
d.set_ylim(0, 850)
d.legend(fontsize=6.6, loc="center right")
d.set_title("(d)", fontsize=8.5, loc="left")
fig.tight_layout(h_pad=1.3, w_pad=1.3)
plotstyle.save(fig, f"{FIG}/spiral_geometry")

print("ndir", ndir, "aux n", len(AUX), "cap n", len(CAP), "aux rotations", (len(AUX) - 1) / ndir,
      "cap rotations", (len(CAP) - 1) / ndir)
for pts, lab in ((pa, "aux"), (pc, "cap")):
    by_dir = {}
    for i, src, r, rel in pts:
        by_dir.setdefault(src, []).append(r)
    g = [abs(b_ - a_) * 10 for s in by_dir.values() for a_, b_ in zip(s, s[1:])]
    print(lab, "gap mm min/median/max", round(min(g), 1), round(float(np.median(g)), 1), round(max(g), 1),
          "visits per dir", {k: len(v) for k, v in by_dir.items()})
